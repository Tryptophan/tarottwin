#!/usr/bin/env node
// Fetch public-domain Rider-Waite-Smith scans from Wikimedia Commons, convert
// to ~600px-wide WebP (ImageMagick `convert`), write public/cards/ATTRIBUTION.md.
// Usage: node scripts/fetch-art.mjs [--force] [--quality=45]
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { mkdir, writeFile, access, stat } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const run = promisify(execFile)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outDir = path.join(root, 'public', 'cards')
const UA = 'tarottwin-art-fetch/1.0 (personal hobby project; Node fetch)'
const API = 'https://commons.wikimedia.org/w/api.php'
const force = process.argv.includes('--force')
const quality = process.argv.find((a) => a.startsWith('--quality='))?.split('=')[1] ?? '45'
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

const MAJORS = [
  ['the-fool', 'Fool'], ['the-magician', 'Magician'], ['the-high-priestess', 'High Priestess'],
  ['the-empress', 'Empress'], ['the-emperor', 'Emperor'], ['the-hierophant', 'Hierophant'],
  ['the-lovers', 'Lovers'], ['the-chariot', 'Chariot'], ['strength', 'Strength'],
  ['the-hermit', 'Hermit'], ['wheel-of-fortune', 'Wheel of Fortune'], ['justice', 'Justice'],
  ['the-hanged-man', 'Hanged Man'], ['death', 'Death'], ['temperance', 'Temperance'],
  ['the-devil', 'Devil'], ['the-tower', 'Tower'], ['the-star', 'Star'], ['the-moon', 'Moon'],
  ['the-sun', 'Sun'], ['judgement', 'Judgement'], ['the-world', 'World'],
]
const SUITS = { wands: 'Wands', cups: 'Cups', swords: 'Swords', pentacles: 'Pents' }
const pad = (n) => String(n).padStart(2, '0')

const cards = []
MAJORS.forEach(([slug, name], i) =>
  cards.push({ id: `major-${pad(i)}-${slug}`, file: `RWS Tarot ${pad(i)} ${name}.jpg` }))
for (const [suit, prefix] of Object.entries(SUITS))
  for (let n = 1; n <= 14; n++) cards.push({ id: `${suit}-${pad(n)}`, file: `${prefix}${pad(n)}.jpg` })

async function get(url, opts = {}) {
  for (let attempt = 0; attempt < 6; attempt++) {
    let res
    try {
      res = await fetch(url, { ...opts, headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(30000) })
    } catch {
      console.warn('  network error/timeout, retrying')
      await sleep(2000)
      continue
    }
    if (res.status === 429 || res.status >= 500) {
      const wait = Number(res.headers.get('retry-after')) * 1000 || 2000 * 2 ** attempt
      console.warn(`  ${res.status}, retrying in ${wait}ms`)
      await sleep(wait)
      continue
    }
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`)
    return res
  }
  throw new Error(`Gave up on ${url}`)
}

async function info(file) {
  const q = new URLSearchParams({
    action: 'query', format: 'json', titles: `File:${file}`,
    prop: 'imageinfo', iiprop: 'url|extmetadata',
  })
  const j = await (await get(`${API}?${q}`)).json()
  const page = Object.values(j.query.pages)[0]
  const ii = page.imageinfo?.[0]
  if (!ii) throw new Error('file not found on Commons')
  const m = ii.extmetadata ?? {}
  return {
    url: ii.url,
    page: `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(file.replaceAll(' ', '_'))}`,
    license: m.LicenseShortName?.value ?? '',
    copyrighted: m.Copyrighted?.value ?? '',
  }
}

const isPD = (i) =>
  /public domain|pd[- ]|cc0/i.test(i.license) && !/^true$/i.test(i.copyrighted)

await mkdir(outDir, { recursive: true })
const rows = []
const failed = []
for (const c of cards) {
  const dest = path.join(outDir, `${c.id}.webp`)
  try {
    const i = await info(c.file)
    await sleep(400)
    if (!isPD(i)) throw new Error(`license not verified as PD: "${i.license}" copyrighted=${i.copyrighted}`)
    let have = false
    try { await access(dest); have = !force } catch {}
    if (!have) {
      const buf = Buffer.from(await (await get(i.url)).arrayBuffer())
      const tmp = path.join(outDir, `.${c.id}.src`)
      await writeFile(tmp, buf)
      await run('convert', [tmp, '-resize', '600x>', '-strip', '-quality', quality, '-define', 'webp:method=6', dest])
      await (await import('node:fs/promises')).unlink(tmp)
      await sleep(600)
    }
    rows.push({ ...c, ...i })
    console.log(`ok   ${c.id}  (${(await stat(dest)).size} B)`)
  } catch (e) {
    failed.push(c.id)
    console.error(`FAIL ${c.id} (${c.file}): ${e.message}`)
  }
}

const md = [
  '# Card art attribution', '',
  'Rider-Waite-Smith deck, illustrated by Pamela Colman Smith (1909, A. E. Waite / William Rider & Son).',
  'Scans from Wikimedia Commons; public domain. Resized to 600px wide WebP. Generated by `scripts/fetch-art.mjs`.', '',
  '| File | Source | License (per Commons) |', '| --- | --- | --- |',
  ...rows.map((r) => `| ${r.id}.webp | [${r.file}](${r.page}) | ${r.license} |`),
  ...(failed.length ? ['', `Not fetched / unverified: ${failed.join(', ')}`] : []), '',
].join('\n')
await writeFile(path.join(outDir, 'ATTRIBUTION.md'), md)
console.log(`\n${rows.length}/${cards.length} succeeded; failed: ${failed.join(', ') || 'none'}`)
process.exitCode = failed.length ? 1 : 0
